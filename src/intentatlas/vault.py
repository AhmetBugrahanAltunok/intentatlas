TRANSIENT_FILE_ERRNOS = {errno.EACCES, errno.EPERM}
TRANSIENT_WINDOWS_ERRORS = {5, 32, 33}
T = TypeVar("T")
MARKDOWN_CONTROL = re.compile(r"([\\`*_{}\[\]()!])")
USER_KINDS = {"memory", "requirement", "decision", "issue", "evidence", "review", "session"}
